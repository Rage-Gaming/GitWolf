#!/usr/bin/env python3
"""Regenerate Sources/GitWolfApp/LanguageLogos.swift: SVG path data from Simple Icons (CC0) for every
`logo("Name", "slug", ...)` in Sources/GitWolfCore/FileIcons.swift. Needs network access."""
import re, sys, urllib.request
ROOT = __file__.rsplit("/Scripts/", 1)[0]
src = open(f"{ROOT}/Sources/GitWolfCore/FileIcons.swift").read()
slugs = sorted(set(re.findall(r'logo\("[^"]+", "([^"]+)"', src)))
out = ("import Foundation\n\n// Generated by Scripts/embed-logos.py from Simple Icons (CC0, https://simpleicons.org). Do not edit by hand.\n"
       "// SVG path data on a 24x24 grid, keyed by Simple Icons slug.\nenum LanguageLogos {\n    static let paths: [String: String] = [\n")
have = dict(re.findall(r'        "([^"]+)": "([^"]+)",', open(f"{ROOT}/Sources/GitWolfApp/LanguageLogos.swift").read()))  # kept as they are
for s in slugs:
    if s in have:
        out += f'        "{s}": "{have[s]}",\n'; continue  # (csharp and css are no longer served by the CDN)
    svg = urllib.request.urlopen(f"https://cdn.jsdelivr.net/npm/simple-icons@13.21.0/icons/{s}.svg").read().decode()
    d = re.findall(r'<path d="([^"]+)"', svg)
    if len(d) != 1: sys.exit(f"{s}: expected one path")
    out += f'        "{s}": "{d[0]}",\n'
open(f"{ROOT}/Sources/GitWolfApp/LanguageLogos.swift", "w").write(out + "    ]\n}\n")
