#!/usr/bin/env python3
"""Collects user-visible string literals from the SwiftUI sources into Resources/en.lproj/Localizable.strings.

SwiftUI looks up literal arguments of Text, Button, Label, Toggle, TextField, Section, Menu, Picker,
.help, .accessibilityLabel/Hint and similar through the app bundle's Localizable.strings, so no code
changes are needed to translate them: copy en.lproj to <lang>.lproj and translate the values.

  Scripts/extract-strings.py            rewrite Resources/en.lproj/Localizable.strings
  Scripts/extract-strings.py --check    exit 1 when the file is out of date (for CI)

Literals with interpolation (\\(x)) are listed in Resources/en.lproj/Interpolated.txt for manual
handling: SwiftUI keys them as "%@"/"%lld" formats, and which one depends on the value's type.
"""
import pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCES = ROOT / "Sources" / "GitWolfApp"
OUT = ROOT / "Resources" / "en.lproj"

CALLS = r'(?:Text|Button|Label|Toggle|TextField|SecureField|Section|Menu|Picker|Link|ContentUnavailableView|DisclosureGroup|GroupBox|Window|CommandMenu)'
MODS = r'(?:help|accessibilityLabel|accessibilityHint|accessibilityValue|navigationTitle|alert|confirmationDialog)'
LITERAL = r'"((?:[^"\\]|\\.)*)"'
PATTERNS = [re.compile(r'\b' + CALLS + r'\(\s*' + LITERAL), re.compile(r'\.' + MODS + r'\(\s*' + LITERAL)]


def collect():
    plain, interpolated = set(), set()
    for path in sorted(SOURCES.rglob("*.swift")):
        for line in path.read_text().splitlines():
            if line.lstrip().startswith("//"):
                continue
            for pattern in PATTERNS:
                for match in pattern.finditer(line):
                    text = match.group(1)
                    if not text.strip() or not re.search(r'[A-Za-z]', text):
                        continue
                    (interpolated if "\\(" in text else plain).add(text)
    return sorted(plain), sorted(interpolated)


def render(plain):
    lines = ['/* Generated by Scripts/extract-strings.py. Copy to <lang>.lproj and translate the values. */', '']
    for text in plain:
        lines.append(f'"{text}" = "{text}";')
    return "\n".join(lines) + "\n"


def main():
    plain, interpolated = collect()
    strings = render(plain)
    notes = "\n".join(interpolated) + "\n"
    target, notes_target = OUT / "Localizable.strings", OUT / "Interpolated.txt"
    if "--check" in sys.argv:
        ok = target.exists() and target.read_text() == strings
        print("strings up to date" if ok else "Localizable.strings is out of date; run Scripts/extract-strings.py")
        sys.exit(0 if ok else 1)
    OUT.mkdir(parents=True, exist_ok=True)
    target.write_text(strings)
    notes_target.write_text(notes)
    print(f"{len(plain)} strings, {len(interpolated)} with interpolation")


main()
